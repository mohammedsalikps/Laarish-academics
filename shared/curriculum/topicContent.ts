import type { GameMeta, SubjectId, Topic, TopicMeta } from './types.js';

/**
 * Full topic content (video, explainer, game, quiz and mentor notes), one module
 * per subject. The browser build turns each into its own chunk that is fetched
 * only when a topic of that subject (or the demo mentor) needs it; everything
 * else in the app works from the small topic index (topicIndex.ts).
 */
const SUBJECT_CONTENT: Record<SubjectId, () => Promise<{ TOPICS: Topic[] }>> = {
  science: () => import('./bySubject/science.js'),
  mathematics: () => import('./bySubject/mathematics.js'),
  english: () => import('./bySubject/english.js'),
  hindi: () => import('./bySubject/hindi.js'),
  kannada: () => import('./bySubject/kannada.js'),
  'social-science': () => import('./bySubject/social-science.js'),
};

export async function loadSubjectTopics(subjectId: SubjectId): Promise<Topic[]> {
  return (await SUBJECT_CONTENT[subjectId]()).TOPICS;
}

/** The index entry for a topic: the fields roadmaps and progress rules use, nothing else. */
export function toTopicMeta(topic: Topic): TopicMeta {
  const { game } = topic.play;
  const gameMeta: GameMeta = game.type === 'friction-experiment' ? { type: game.type, surfaces: game.surfaces.map(({ id, name }) => ({ id, name })) } : { type: game.type };
  return {
    id: topic.id,
    subjectId: topic.subjectId,
    lessonId: topic.lessonId,
    order: topic.order,
    title: topic.title,
    summary: topic.summary,
    language: topic.language,
    icon: topic.icon,
    estimatedMinutes: topic.estimatedMinutes,
    ...(topic.difficulty !== undefined && { difficulty: topic.difficulty }),
    ...(topic.prerequisites && { prerequisites: topic.prerequisites }),
    ...(topic.mastery && { mastery: topic.mastery }),
    watch: { video: { id: topic.watch.video.id, status: topic.watch.video.status } },
    play: { title: topic.play.title, assessed: topic.play.assessed, weight: topic.play.weight, game: gameMeta },
    practice: { weight: topic.practice.weight, questions: topic.practice.questions.map((q) => ({ id: q.id })) },
  };
}

/** Source of topicIndex.ts (one topic per line), written by `npm run curriculum:index`. */
export function renderTopicIndex(topics: Topic[]): string {
  return [
    '// Generated by `npm run curriculum:index` from the topic files. Do not edit by hand.',
    "import type { TopicMeta } from './types.js';",
    '',
    'export const TOPIC_INDEX: TopicMeta[] = [',
    ...topics.map((t) => `  ${JSON.stringify(toTopicMeta(t))},`),
    '];',
    '',
  ].join('\n');
}
