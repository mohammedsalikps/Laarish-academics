/** Coach lines for the round-based games (number-line, area-grid, clock, bar-chart, fraction-builder), which send {explanation} and {hint}. */
function roundCoach(start: string, complete: string, perfect: string, correct = 'Yes! {explanation}', incorrect = 'Not yet. {hint}'): CoachScript {
  return { start, 'round-correct': correct, 'round-incorrect': incorrect, complete, 'complete:perfect': perfect };
}

