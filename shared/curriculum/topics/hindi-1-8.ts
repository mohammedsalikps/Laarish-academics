/* ----------------------------------------------------------------- helpers */

const chips = (...words: string[]): IllustrationSpec => ({ kind: 'word-chips', words });
const pic = (icon: IconKey, tone: 'primary' | 'success' | 'reward' | 'coral' | 'sky' = 'primary'): IllustrationSpec => ({ kind: 'icon', icon, tone });

interface HindiTopicSeed extends Omit<Topic, 'subjectId' | 'language' | 'watch' | 'play' | 'practice'> {
  watch: Omit<TopicWatch, 'video'>;
  play: Omit<TopicPlay, 'assessed' | 'weight'>;
  practice: QuizQuestion[];
}

/** A Hindi topic: no official video yet, an assessed game (weight 1) and a practice quiz (weight 3). */
function hindiTopic(t: HindiTopicSeed): Topic {
  return {
    ...t,
    subjectId: 'hindi',
    language: 'hi',
    watch: { video: missingVideo(`video-${t.id}`, t.title), ...t.watch },
    play: { ...t.play, assessed: true, weight: 1 },
    practice: { weight: 3, questions: t.practice },
  };
}

interface CoachLines {
  start: string;
  correct: string;
  incorrect: string;
  complete: string;
  perfect: string;
}
const matchCoach = (c: CoachLines): CoachScript => ({ start: c.start, 'match-correct': c.correct, 'match-incorrect': c.incorrect, complete: c.complete, 'complete:perfect': c.perfect });
const sortCoach = (c: CoachLines): CoachScript => ({ start: c.start, 'sort-correct': c.correct, 'sort-incorrect': c.incorrect, complete: c.complete, 'complete:perfect': c.perfect });

