import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { LESSONS, SUBJECTS, TOPICS } from '../../shared/curriculum/index.js';
import { parseManifest } from '../../shared/media/manifest.js';
import { buildVideoQueue, type VideoJob } from '../../shared/media/videoQueue.js';

/**
 * `npm run videos:queue`: writes content/video-queue.json (every topic's job, with its prompt and
 * captions, in production order) and docs/VIDEO-CONTENT-STATUS.md (coverage per lesson).
 * A video counts as done only when public/media/manifest.json points at a real file; failures come
 * from content/video-log.json, which `npm run videos:ingest` writes. Nothing is invented here.
 */

type LogEntry = { status: 'completed' | 'failed'; provider?: string; model?: string; error?: string; at: string };
const root = process.cwd();
const read = <T>(path: string, fallback: T): T => (existsSync(path) ? (JSON.parse(readFileSync(path, 'utf8')) as T) : fallback);

const manifest = parseManifest(read(join(root, 'public/media/manifest.json'), { videos: {} }));
const log = read<{ entries: Record<string, LogEntry> }>(join(root, 'content/video-log.json'), { entries: {} }).entries;
const jobs = buildVideoQueue(TOPICS, LESSONS, SUBJECTS);

type Status = 'completed' | 'pending' | 'failed';
const statusOf = (job: VideoJob): Status => (manifest.videos[job.videoId] ? 'completed' : log[job.videoId]?.status === 'failed' ? 'failed' : 'pending');

mkdirSync(join(root, 'content'), { recursive: true });
writeFileSync(
  join(root, 'content/video-queue.json'),
  JSON.stringify({ generatedAt: new Date().toISOString().slice(0, 10), jobs: jobs.map((j) => ({ ...j, status: statusOf(j) })) }, null, 2) + '\n',
);

// ---------------------------------------------------------------- coverage report
const count = (s: Status, list = jobs) => list.filter((j) => statusOf(j) === s).length;
const subjectName = new Map(SUBJECTS.map((s) => [s.id, s.name]));
const lines: string[] = [];
lines.push('# Lesson video coverage', '');
lines.push(`Generated by \`npm run videos:queue\` on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.`, '');
lines.push(
  'A video counts as **completed** only when `public/media/manifest.json` points at a real, checked file',
  '(`npm run media:check`). Until then the Watch step shows the clearly labelled animated explainer.',
  '',
);
lines.push('## Summary', '');
lines.push('| | Topics (Watch videos) | Completed | Pending | Failed |', '|---|---|---|---|---|');
for (const p of [1, 2, 3] as const) {
  const list = jobs.filter((j) => j.priority === p);
  const label = p === 1 ? 'Priority 1: Class 6 Science and Mathematics' : p === 2 ? 'Priority 2: demonstration lessons' : 'Priority 3: all other lessons';
  lines.push(`| ${label} | ${list.length} | ${count('completed', list)} | ${count('pending', list)} | ${count('failed', list)} |`);
}
lines.push(`| **All topics** | **${jobs.length}** | **${count('completed')}** | **${count('pending')}** | **${count('failed')}** |`, '');

const withTopics = new Set(jobs.map((j) => j.lessonId));
const unwritten = LESSONS.filter((l) => !withTopics.has(l.id));
lines.push(
  `Lessons: ${LESSONS.length} in the catalogue. ${withTopics.size} have topics, so each has one video per topic. ` +
    `${unwritten.length} are planned lessons with no content yet; they get videos once their topics are written.`,
  '',
);

lines.push('## By lesson', '');
lines.push('| Priority | Subject | Class | Lesson | Topics | Completed | Pending | Failed |', '|---|---|---|---|---|---|---|---|');
const byLesson = new Map<string, VideoJob[]>();
for (const j of jobs) byLesson.set(j.lessonId, [...(byLesson.get(j.lessonId) ?? []), j]);
for (const [, list] of byLesson) {
  const j = list[0];
  const cls = j.grades[0] === j.grades[1] ? `${j.grades[0]}` : `${j.grades[0]}-${j.grades[1]}`;
  lines.push(`| ${j.priority} | ${j.subjectName} | ${cls} | ${j.lessonTitle} | ${list.length} | ${count('completed', list)} | ${count('pending', list)} | ${count('failed', list)} |`);
}
lines.push('', '## Planned lessons without content (no video yet)', '');
lines.push(unwritten.map((l) => `${subjectName.get(l.subjectId) ?? l.subjectId}: ${l.title}`).join(' · ') || 'None.', '');

const failed = jobs.filter((j) => statusOf(j) === 'failed');
if (failed.length) {
  lines.push('## Failed', '');
  for (const j of failed) lines.push(`- \`${j.videoId}\` (${j.lessonTitle} · ${j.topicTitle}): ${log[j.videoId]?.error ?? 'unknown error'}`);
  lines.push('');
}

writeFileSync(join(root, 'docs/VIDEO-CONTENT-STATUS.coverage.md'), lines.join('\n'));
console.log(`queue: ${jobs.length} jobs (${count('completed')} completed, ${count('pending')} pending, ${count('failed')} failed); ${unwritten.length} lessons without content`);
