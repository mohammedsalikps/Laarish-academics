import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { GRADES, LESSONS, SUBJECTS, TOPICS, getBranch, getLevel, topicReadiness, type Lesson } from '../../shared/curriculum/index.js';

/**
 * Curriculum audit report: `npm run curriculum:report`
 *
 * Writes docs/curriculum-status.md from the curriculum data: counts per subject
 * and class, readiness of every topic (video, game, quiz), how each lesson is
 * mapped to an official source and what still needs human review. Counts come
 * only from real data: planned lessons have no topics and are never counted as
 * playable.
 */

const lines: string[] = ['# Curriculum status', '', 'Generated by `npm run curriculum:report` from `shared/curriculum`. Do not edit by hand. Sources: [curriculum-sources.md](curriculum-sources.md).', ''];
const ready = (l: Lesson) => l.status === 'ready';
const topicsOf = (lessons: Lesson[]) => lessons.flatMap((l) => l.topicIds);
const readiness = TOPICS.map(topicReadiness);
const playable = TOPICS.filter((t) => LESSONS.some((l) => ready(l) && l.topicIds.includes(t.id)));
const byStatus = (lessons: Lesson[], status: string) => lessons.filter((l) => l.source?.status === status).length;

lines.push(
  '## Totals',
  '',
  '| Measure | Count |',
  '|---|---|',
  `| Classes supported | ${GRADES.length} (Classes ${GRADES[0]}-${GRADES[GRADES.length - 1]}) |`,
  `| Subjects | ${SUBJECTS.length} |`,
  `| Branches (distinct per subject) | ${SUBJECTS.reduce((n, s) => n + (s.branches?.length ?? 0), 0)} |`,
  `| Class × branch units with at least one lesson | ${new Set(LESSONS.map((l) => `${l.subjectId}/${l.levelId}/${l.branchId}`)).size} |`,
  `| Lessons | ${LESSONS.length} (${LESSONS.filter(ready).length} playable, ${LESSONS.filter((l) => !ready(l)).length} planned) |`,
  `| Topics | ${TOPICS.length} |`,
  `| Fully playable topics (Watch, Play and Practice complete) | ${playable.length} |`,
  `| Topics with a verified official video | ${readiness.filter((r) => r.video === 'ready').length} |`,
  `| Topics using the temporary animated explainer | ${readiness.filter((r) => r.video === 'explainer').length} |`,
  `| Topics missing a game | 0 (every topic has a game; ${readiness.filter((r) => r.game === 'exploratory').length} exploratory, not assessed) |`,
  `| Topics missing a quiz (fewer than 3 questions) | ${readiness.filter((r) => r.quiz === 'missing').length} |`,
  `| Lessons mapped to a verified official chapter by its title (aligned; chapter content not yet checked by a teacher) | ${byStatus(LESSONS, 'aligned')} |`,
  `| Lessons curriculum-inspired (stage and themes, no single verified unit) | ${byStatus(LESSONS, 'curriculum-inspired')} |`,
  `| Lessons proposed (not checked against an official syllabus) | ${byStatus(LESSONS, 'proposed')} |`,
  `| Lessons awaiting teacher review | ${LESSONS.filter((l) => l.review?.teacher === 'pending').length} |`,
  `| Lessons awaiting native-speaker review (Hindi, Kannada) | ${LESSONS.filter((l) => l.review?.nativeSpeaker === 'pending').length} |`,
  '',
  '## By subject and class',
  '',
  `| Subject | ${GRADES.map((g) => `Class ${g}`).join(' | ')} | Total |`,
  `|---|${GRADES.map(() => '---').join('|')}|---|`,
);
for (const subject of SUBJECTS) {
  const cells = GRADES.map((g) => {
    const lessons = LESSONS.filter((l) => l.subjectId === subject.id && l.grades[0] === g);
    return `${lessons.filter(ready).length}/${lessons.length} · ${topicsOf(lessons.filter(ready)).length}t`;
  });
  const all = LESSONS.filter((l) => l.subjectId === subject.id);
  lines.push(`| ${subject.name} | ${cells.join(' | ')} | ${all.filter(ready).length}/${all.length} · ${topicsOf(all.filter(ready)).length}t |`);
}
lines.push('', 'Cells: playable lessons / all lessons · playable topics.', '');

lines.push('## Lesson map', '');
for (const subject of SUBJECTS) {
  lines.push(`### ${subject.name}`, '');
  for (const level of subject.levels ?? []) {
    const inClass = LESSONS.filter((l) => l.subjectId === subject.id && l.levelId === level.id);
    if (!inClass.length) {
      lines.push(`**${level.title}**: no lessons yet.`, '');
      continue;
    }
    lines.push(`**${level.title}**`, '', '| Branch | Lesson | Status | Topics | Source | Alignment |', '|---|---|---|---|---|---|');
    for (const branch of subject.branches ?? []) {
      for (const l of inClass.filter((x) => x.branchId === branch.id).sort((a, b) => a.order - b.order)) {
        const s = l.source;
        lines.push(
          `| ${getBranch(subject.id, branch.id)?.title} | ${l.order}. ${l.title} | ${ready(l) ? 'Playable' : 'Planned'} | ${l.topicIds.length} | ${s ? `${s.framework} ${s.document}${s.unit ? `: ${s.unit}` : ''} (${s.academicYear})` : '—'} | ${s?.status ?? 'missing'} |`,
        );
      }
    }
    lines.push('');
  }
  const unplaced = LESSONS.filter((l) => l.subjectId === subject.id && !getLevel(subject.id, l.levelId));
  if (unplaced.length) lines.push(`Not placed in a class: ${unplaced.map((l) => l.title).join(', ')}`, '');
}

lines.push('## Topic readiness', '', '| Subject | Class | Lesson | Topic | Video | Game | Quiz |', '|---|---|---|---|---|---|---|');
for (const topic of TOPICS) {
  const r = topicReadiness(topic);
  const lesson = LESSONS.find((l) => l.id === topic.lessonId);
  const subject = SUBJECTS.find((s) => s.id === topic.subjectId);
  lines.push(
    `| ${subject?.name} | ${lesson?.grades[0] ?? '?'} | ${lesson?.title} | ${topic.title} | ${r.video === 'ready' ? 'Official video' : 'Temporary explainer'} | ${topic.play.game.type}${r.game === 'exploratory' ? ' (exploratory)' : ''} | ${r.quiz === 'ready' ? `${topic.practice.questions.length} questions` : 'Missing'} |`,
  );
}

const out = join(process.cwd(), 'docs', 'curriculum-status.md');
writeFileSync(out, `${lines.join('\n')}\n`);
console.log(`Wrote docs/curriculum-status.md: ${SUBJECTS.length} subjects, ${LESSONS.length} lessons (${LESSONS.filter(ready).length} playable), ${TOPICS.length} topics (${playable.length} playable).`);
